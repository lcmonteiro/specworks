"""Design diagrams: D2 sources rendered to SVG with one shared look.

A change keeps diagram sources next to its design::

    <change>/diagrams/reset-flow.d2     source (short text, reviewed in diffs)
    <change>/diagrams/reset-flow.svg    generated by `specworks diagrams`

design.md embeds the SVG (``![Reset flow](diagrams/reset-flow.svg)``). Each
generated SVG carries a stamp with the hash of its source and render settings,
so a stale or hand-edited SVG is detected without relying on file times (which
git does not preserve).

Rendering goes through ``d2-bin`` (its pinned official D2 release and its
``render_file``); this module adds what is specific to specworks: the settings
from the config file, the stamp, and the ``SPECWORKS_D2`` override. Checking
needs no d2.
"""

from __future__ import annotations

import hashlib
import os
import re
import shutil
from dataclasses import dataclass
from pathlib import Path

import d2_bin

from .config import DiagramSettings

DIAGRAMS_DIR = "diagrams"
STAMP_RE = re.compile(r"<!-- specworks:d2 sha256=(?P<hash>[0-9a-f]{64}) -->")
INSTALL_HINT = (
    "specworks normally installs d2 with its d2-bin dependency; reinstall it (`uv tool install --reinstall specworks`), "
    "or install D2 yourself (https://d2lang.com/tour/install) or set SPECWORKS_D2 to its path"
)


class DiagramError(Exception):
    """Raised when D2 is missing or fails to render a diagram."""


@dataclass
class Diagram:
    source: Path

    @property
    def svg(self) -> Path:
        return self.source.with_suffix(".svg")


def bundled_d2() -> str | None:
    """The d2 binary installed by the d2-bin dependency, if it is there."""
    try:
        return d2_bin.executable()
    except FileNotFoundError:
        return None


def find_d2() -> tuple[str | None, str]:
    """(path, where) - SPECWORKS_D2 first, then d2-bin's pinned release, then PATH."""
    if os.environ.get("SPECWORKS_D2"):
        return os.environ["SPECWORKS_D2"], "SPECWORKS_D2"
    if path := bundled_d2():
        return path, "d2-bin"
    if path := shutil.which("d2"):
        return path, "PATH"
    return None, "missing"


def diagrams_in(folder: Path) -> list[Diagram]:
    root = folder / DIAGRAMS_DIR
    return [Diagram(p) for p in sorted(root.glob("*.d2"))] if root.is_dir() else []


def d2_args(settings: DiagramSettings) -> list[str]:
    return settings.options().args()


def source_hash(diagram: Diagram, settings: DiagramSettings) -> str:
    """Hash of the source text and the render settings: either changing makes the SVG stale."""
    digest = hashlib.sha256(diagram.source.read_bytes())
    digest.update("\0".join(d2_args(settings)).encode())
    return digest.hexdigest()


def state(diagram: Diagram, settings: DiagramSettings) -> str:
    """``ok``, ``missing`` (no SVG) or ``stale`` (source or settings changed, or the SVG was not generated)."""
    if not diagram.svg.is_file():
        return "missing"
    match = STAMP_RE.search(diagram.svg.read_text(encoding="utf-8", errors="replace")[:4096])
    return "ok" if match and match.group("hash") == source_hash(diagram, settings) else "stale"


def stamp(svg_text: str, digest: str) -> str:
    mark = f"<!-- specworks:d2 sha256={digest} -->"
    if svg_text.startswith("<?xml"):
        end = svg_text.index("?>") + 2
        return svg_text[:end] + mark + svg_text[end:]
    return mark + svg_text


def render(diagram: Diagram, settings: DiagramSettings, d2: str | None = None) -> None:
    d2 = d2 or find_d2()[0]
    if d2 is None:
        raise DiagramError(f"cannot render {diagram.source.name}: d2 is not installed; {INSTALL_HINT}")
    try:
        d2_bin.render_file(diagram.source, diagram.svg, settings.options(), d2=d2)
    except d2_bin.D2Error as exc:
        raise DiagramError(str(exc)) from exc
    except OSError as exc:  # SPECWORKS_D2 points at something that does not run
        raise DiagramError(f"cannot run d2 ({d2}) on {diagram.source.name}: {exc}") from exc
    diagram.svg.write_text(stamp(diagram.svg.read_text(encoding="utf-8"), source_hash(diagram, settings)), encoding="utf-8")


def referenced_images(markdown: str) -> list[str]:
    """Relative image paths used in a markdown file (``![alt](path)``)."""
    return [m.group(1) for m in re.finditer(r"!\[[^\]]*\]\(\s*([^)\s]+)", markdown) if "://" not in m.group(1)]
