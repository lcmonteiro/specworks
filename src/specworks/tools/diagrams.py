"""Design diagrams: D2 sources rendered to SVG with one shared look.

A change keeps diagram sources next to its design::

    <change>/diagrams/reset-flow.d2     source (short text, reviewed in diffs)
    <change>/diagrams/reset-flow.svg    generated by `specworks diagrams`

design.md embeds the SVG (``![Reset flow](diagrams/reset-flow.svg)``). Each
generated SVG carries a stamp with the hash of its source and render settings,
so a stale or hand-edited SVG is detected without relying on file times (which
git does not preserve).

pyd2 provides d2 and renders; this module adds what is specific to specworks:
the settings from the config file and the stamp. ``SPECWORKS_D2`` runs another
d2 instead of pyd2's (tests use it for a fake d2). Checking needs no d2.
"""

from __future__ import annotations

import hashlib
import os
import re
from dataclasses import dataclass
from pathlib import Path

import pyd2

from ..core.config import DiagramSettings
from ..core.errors import SpecworksError

DIAGRAMS_DIR = "diagrams"
STAMP = "<!-- specworks:d2 sha256={} -->"
STAMP_RE = re.compile(re.escape(STAMP).replace(r"\{\}", r"(?P<hash>[0-9a-f]{64})"))


class DiagramError(SpecworksError):
    """Raised when D2 is missing or fails to render a diagram."""


@dataclass
class Diagram:
    source: Path

    @property
    def svg(self) -> Path:
        return self.source.with_suffix(".svg")


def env_d2() -> str | None:
    return os.environ.get("SPECWORKS_D2") or None


# @req REQ-INTEG-003
def find_d2() -> tuple[str | None, str]:
    """(path, where) of the d2 that renders: SPECWORKS_D2 if set, else pyd2's (None if pyd2 has none)."""
    if d2 := env_d2():
        return d2, "SPECWORKS_D2"
    try:
        return pyd2.executable(), "pyd2"
    except FileNotFoundError:
        return None, "missing"


def diagrams_in(folder: Path) -> list[Diagram]:
    root = folder / DIAGRAMS_DIR
    return [Diagram(p) for p in sorted(root.glob("*.d2"))] if root.is_dir() else []


# @req REQ-INTEG-001
def source_hash(diagram: Diagram, settings: DiagramSettings) -> str:
    """Hash of the source text and the render settings: either changing makes the SVG stale."""
    digest = hashlib.sha256(diagram.source.read_bytes())
    digest.update("\0".join(settings.options().args()).encode())
    return digest.hexdigest()


# @req REQ-INTEG-002
def state(diagram: Diagram, settings: DiagramSettings) -> str:
    """``ok``, ``missing`` (no SVG) or ``stale`` (source or settings changed, or the SVG was not generated)."""
    if not diagram.svg.is_file():
        return "missing"
    match = STAMP_RE.search(diagram.svg.read_text(encoding="utf-8", errors="replace")[:4096])
    return "ok" if match and match.group("hash") == source_hash(diagram, settings) else "stale"


# @req REQ-INTEG-001
def stamp(svg_text: str, digest: str) -> str:
    mark = STAMP.format(digest)
    if svg_text.startswith("<?xml"):
        if (end := svg_text.find("?>")) < 0:
            raise ValueError("the SVG's <?xml declaration is not closed")
        return svg_text[: end + 2] + mark + svg_text[end + 2 :]
    return mark + svg_text


# @req REQ-INTEG-001, REQ-INTEG-003
def render(diagram: Diagram, settings: DiagramSettings) -> None:
    try:
        pyd2.render_file(diagram.source, diagram.svg, settings.options(), d2=env_d2())
    except pyd2.D2Error as exc:
        raise DiagramError(str(exc)) from exc
    except OSError as exc:  # pyd2 has no binary, or SPECWORKS_D2 does not run
        raise DiagramError(f"cannot render {diagram.source.name}: {exc}") from exc
    # d2 succeeded, but what it wrote must still be an SVG that can be stamped.
    name = diagram.source.name
    try:
        diagram.svg.write_text(stamp(diagram.svg.read_text(encoding="utf-8"), source_hash(diagram, settings)), encoding="utf-8")
    except UnicodeDecodeError:
        raise DiagramError(f"cannot render {name}: the SVG d2 wrote is not UTF-8 text") from None
    except (OSError, ValueError) as exc:
        raise DiagramError(f"cannot render {name}: {exc}") from None


def referenced_images(markdown: str) -> list[str]:
    """Relative image paths used in a markdown file (``![alt](path)``)."""
    return [m.group(1) for m in re.finditer(r"!\[[^\]]*\]\(\s*([^)\s]+)", markdown) if "://" not in m.group(1)]
